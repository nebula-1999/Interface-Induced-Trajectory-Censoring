#!/usr/bin/env python3
"""从 paper/sections/*.tex 重新生成 writeup/paper_draft.md。

方向是刻意的：**LaTeX 是唯一事实来源**，Markdown 是派生产物。
早先是反过来的（convert.py：md → tex），结果是所有手工修的 LaTeX
——补回的 §5.6.1、重写的 §7、降级过的措辞——在 md 里全部丢失，
两份文稿静默分叉。谁再从旧 md 重新生成一次，改动就没了。
"""
import os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ORDER = [
    ("abstract",        "\\section{Abstract}"),
    ("01_intro",        None), ("02_related", None), ("03_setup", None),
    ("04_control",      None), ("05_results", None), ("06_discussion", None),
    ("07_limitations",  None), ("08_conclusion", None),
    ("A_errata",        "\\section*{Appendix A --- Data Errata}"),
    ("B_repro",         "\\section*{Appendix B --- Reproducibility}"),
]
HEADER = """# Interface-Induced Trajectory Censoring

**Tool-call interfaces silently decouple observed agent behaviour from model
capability, and contaminate reinforcement learning**

Wenbo Wang · City University of Hong Kong · `wenbwang3-c@my.cityu.edu.hk`

> **Generated from `paper/sections/*.tex`, which is the single source of truth.**
> Do not edit this file by hand — edits are lost on the next regeneration.
> To change the paper, edit the `.tex` and re-run `python paper/regen_draft.py`.
>
> Figures, table rules and cross-references render correctly only in the compiled PDF;
> this file exists for reading and diffing on GitHub.

---

"""

def main():
    buf = []
    for name, pre in ORDER:
        p = os.path.join(HERE, "sections", name + ".tex")
        if not os.path.exists(p):
            sys.exit(f"缺 {p}")
        if pre: buf.append(pre)
        buf.append(open(p, encoding="utf-8").read())
    tmp = os.path.join(HERE, ".all.tex")
    open(tmp, "w", encoding="utf-8").write("\n".join(buf))
    try:
        md = subprocess.run(["pandoc", "-f", "latex", "-t", "gfm", "--wrap=preserve", tmp],
                            capture_output=True, text=True, check=True).stdout
    finally:
        os.remove(tmp)
    out = os.path.join(HERE, "..", "writeup", "paper_draft.md")
    open(out, "w", encoding="utf-8").write(HEADER + md)
    print(f"writeup/paper_draft.md 已重新生成：{len(md.split())} 词，{len(md.splitlines())} 行")

if __name__ == "__main__":
    main()
